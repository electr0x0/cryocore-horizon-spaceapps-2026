  await page.getByRole('button', { name: 'Recenter Bangladesh' }).click();
  await expect(page.locator('.metric-grid')).toContainText('284.0');
  await page.getByRole('button', { name: '2020', exact: true }).click();
  await expect(page.locator('.metric-grid')).toContainText('86.0');
  await page.getByRole('slider', { name: 'Observation year' }).press('End');
  await expect(page.locator('.metric-grid')).toContainText('284.0');
  await page.getByRole('button', { name: 'Play timeline' }).click();
  await expect(page.getByRole('button', { name: 'Pause timeline' })).toBeVisible();
