  await page.getByRole('button', { name: 'Pause timeline' }).click();
  await page.getByRole('button', { name: '2026', exact: true }).click();
  await page.getByRole('button', { name: 'Toggle map layers' }).click();
  await page.getByLabel('Simulated detections', { exact: true }).uncheck();
  await expect(page.locator('.leaflet-overlay-pane path[stroke-dasharray="5 6"]')).toHaveCount(0);
  await page.getByLabel('Simulated detections', { exact: true }).check();
  await page.getByLabel('Satellite basemap', { exact: true }).uncheck();
  await expect(page.locator('.leaflet-image-layer').nth(1)).toHaveCSS('opacity','0.2');
  await page.getByLabel('Satellite basemap', { exact: true }).check();
  await page.getByRole('button', { name: 'Toggle map layers' }).click();
  await page.getByRole('tab', { name: 'Before / after' }).click();
